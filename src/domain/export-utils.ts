/**
 * Export Utilities
 * 
 * CSV generation and print formatting for attendance reports,
 * eligibility lists, and audit logs.
 */

export interface ExportColumn<T> {
  header: string;
  accessor: (item: T) => string | number;
}

/**
 * Generate CSV content from typed data
 */
export function generateCSV<T>(
  data: T[],
  columns: ExportColumn<T>[],
): string {
  const headers = columns.map(c => escapeCSV(c.header)).join(',');
  const rows = data.map(item =>
    columns.map(col => escapeCSV(String(col.accessor(item)))).join(',')
  );
  return [headers, ...rows].join('\n');
}

function escapeCSV(value: string): string {
  if (value.includes(',') || value.includes('"') || value.includes('\n')) {
    return `"${value.replace(/"/g, '""')}"`;
  }
  return value;
}

/**
 * Download CSV as a file
 */
export function downloadCSV(csv: string, filename: string): void {
  const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', `${filename}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Open print dialog for a formatted table
 */
export function printTable<T>(
  title: string,
  data: T[],
  columns: ExportColumn<T>[],
  metadata?: { generatedBy?: string; date?: string; institution?: string }
): void {
  const rows = data.map(item =>
    columns.map(col => String(col.accessor(item)))
  );

  const html = `
    <!DOCTYPE html>
    <html>
    <head>
      <title>${title}</title>
      <style>
        @media print {
          body { font-family: 'Segoe UI', sans-serif; font-size: 11px; color: #1a1a1a; }
          h1 { font-size: 16px; margin-bottom: 4px; }
          .meta { font-size: 10px; color: #666; margin-bottom: 12px; }
          table { width: 100%; border-collapse: collapse; }
          th { background: #f4f4f5; text-align: left; padding: 6px 8px; border: 1px solid #e4e4e7; font-weight: 600; font-size: 10px; }
          td { padding: 5px 8px; border: 1px solid #e4e4e7; }
          tr:nth-child(even) { background: #fafafa; }
          .footer { margin-top: 16px; font-size: 9px; color: #999; text-align: center; }
        }
      </style>
    </head>
    <body>
      <h1>${title}</h1>
      <div class="meta">
        ${metadata?.institution ? `<div>${metadata.institution}</div>` : ''}
        ${metadata?.date ? `<div>Date: ${metadata.date}</div>` : ''}
        ${metadata?.generatedBy ? `<div>Generated by: ${metadata.generatedBy}</div>` : ''}
        <div>Total Records: ${data.length}</div>
      </div>
      <table>
        <thead>
          <tr>${columns.map(c => `<th>${c.header}</th>`).join('')}</tr>
        </thead>
        <tbody>
          ${rows.map(row => `<tr>${row.map(cell => `<td>${cell}</td>`).join('')}</tr>`).join('')}
        </tbody>
      </table>
      <div class="footer">BCAMS — Biometric Class Attendance Management System</div>
      <script>window.onload = function() { window.print(); }</script>
    </body>
    </html>
  `;

  const printWindow = window.open('', '_blank', 'width=800,height=600');
  if (printWindow) {
    printWindow.document.write(html);
    printWindow.document.close();
  }
}
